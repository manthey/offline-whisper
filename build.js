const esbuild = require('esbuild');
const fs = require('fs');
const coverage = process.argv.includes('--coverage');

async function build() {
  // The transcription worker is bundled separately and embedded in main.js as
  // a string: Obsidian plugins distribute a single main.js, and on mobile the
  // worker is started from a blob URL built out of that string. The worker
  // must not reference 'obsidian', which is not resolvable in a worker.
  const workerBuild = await esbuild.build({
    entryPoints: ['src/transcription-worker.js'],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    minify: false,
    sourcemap: false,
    logLevel: 'info',
  });
  const workerSource = workerBuild.outputFiles[0].text;
  fs.writeFileSync(
    'src/generated-worker-source.js',
    '// Generated by build.js: the bundled transcription worker as a string.\n' +
      '// Do not edit this file; run `node build.js` to regenerate it.\n' +
      'module.exports = ' +
      JSON.stringify(workerSource) +
      ';\n',
  );
  console.log(`Worker bundle generated (${Math.round(workerSource.length / 1024)} KB)`);

  await esbuild.build({
    entryPoints: ['src/main.js'],
    bundle: true,
    outfile: 'main.js',
    format: 'cjs',
    platform: 'browser',
    target: 'es2020',
    external: ['obsidian'],
    // The main thread never runs transformers.js inference: mobile inference
    // happens inside the embedded worker bundle above, and desktop cleanup
    // uses the llama-server process. Substituting a stub here keeps a second
    // copy of the library out of main.js; the one main-thread consumer (the
    // desktop Clear Cache handler) only clears a cache directory.
    alias: { '@huggingface/transformers': './stub-transformers.js' },
    minify: false,
    sourcemap: coverage ? 'inline' : false,
    sourcesContent: true,
  });
  console.log(`Build complete`);
}

build().catch((err) => {
  console.error(err);
  process.exit(1);
});
